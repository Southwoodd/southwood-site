def M(label, value, old=None):
    m = {'label': label, 'value': value}
    if old:
        m['old'] = old
    # порядок ключей как в исходнике: label, old, value
    return {'label': m['label'], **({'old': m['old']} if 'old' in m else {}), 'value': m['value']}

