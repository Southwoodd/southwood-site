import { byId, initial, itemPrice, fmtRange, type R } from '../pricing/model';

const price = (id: string, over: Record<string, unknown> = {}): R => itemPrice({ ...initial(), sel: [id], ...over } as any, id);
const show = (id: string, over: Record<string, unknown> = {}) => {
  const it = byId[id];
  if (it.tbd) return 'после разбора';
  if (it.pct) return `+${Math.round(it.pct * 100)}%`;
  return (it.from ? 'от ' : '') + fmtRange(price(id, over));
};
const fromOf = (ids: string[]) => Math.min(...ids.map((id) => price(id)[0]));

